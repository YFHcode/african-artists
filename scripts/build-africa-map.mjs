// build-africa-map.mjs — writes src/content/africa-map.ts: Africa as SVG paths
// grouped by the site's regions, from Natural Earth 1:110m (public domain, via
// the world-atlas package). Run rarely (when regions change); its packages are
// not dependencies of the site:
//   npm i --no-save world-atlas@2.0.2 topojson-client@3.1.0 d3-geo@3.1.1
//   node scripts/build-africa-map.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

import * as d3 from 'd3-geo';
import * as topojson from 'topojson-client';

const world = JSON.parse(readFileSync(createRequire(import.meta.url).resolve('world-atlas/countries-110m.json'), 'utf8'));

// ISO 3166-1 numeric -> alpha-2, for every country drawn. Names are checked against the data below.
const ISO = {
  '012': ['DZ', 'Algeria'], '024': ['AO', 'Angola'], '204': ['BJ', 'Benin'], '072': ['BW', 'Botswana'], '854': ['BF', 'Burkina Faso'],
  '108': ['BI', 'Burundi'], '120': ['CM', 'Cameroon'], '140': ['CF', 'Central African Rep.'], '148': ['TD', 'Chad'], '178': ['CG', 'Congo'],
  '180': ['CD', 'Dem. Rep. Congo'], '384': ['CI', "Côte d'Ivoire"], '262': ['DJ', 'Djibouti'], '818': ['EG', 'Egypt'], '226': ['GQ', 'Eq. Guinea'],
  '232': ['ER', 'Eritrea'], '748': ['SZ', 'eSwatini'], '231': ['ET', 'Ethiopia'], '266': ['GA', 'Gabon'], '270': ['GM', 'Gambia'], '288': ['GH', 'Ghana'],
  '324': ['GN', 'Guinea'], '624': ['GW', 'Guinea-Bissau'], '404': ['KE', 'Kenya'], '426': ['LS', 'Lesotho'], '430': ['LR', 'Liberia'], '434': ['LY', 'Libya'],
  '450': ['MG', 'Madagascar'], '454': ['MW', 'Malawi'], '466': ['ML', 'Mali'], '478': ['MR', 'Mauritania'], '504': ['MA', 'Morocco'], '508': ['MZ', 'Mozambique'],
  '516': ['NA', 'Namibia'], '562': ['NE', 'Niger'], '566': ['NG', 'Nigeria'], '646': ['RW', 'Rwanda'], '686': ['SN', 'Senegal'], '694': ['SL', 'Sierra Leone'],
  '706': ['SO', 'Somalia'], '710': ['ZA', 'South Africa'], '728': ['SS', 'S. Sudan'], '729': ['SD', 'Sudan'], '834': ['TZ', 'Tanzania'], '768': ['TG', 'Togo'],
  '788': ['TN', 'Tunisia'], '800': ['UG', 'Uganda'], '732': ['EH', 'W. Sahara'], '894': ['ZM', 'Zambia'], '716': ['ZW', 'Zimbabwe'],
};
// The site's regions (src/content/catalog.ts), plus where the countries it does not tag sit, for a complete picture.
const REGIONS = {
  'north-africa': ['DZ', 'EG', 'LY', 'MA', 'SD', 'TN'],
  'west-africa': ['BF', 'BJ', 'CI', 'CV', 'GH', 'GM', 'GN', 'LR', 'ML', 'NG', 'SL', 'SN', 'TG', 'MR', 'NE', 'GW'],
  'central-africa': ['AO', 'CD', 'CF', 'CG', 'CM', 'GA', 'GQ', 'TD'],
  'east-africa': ['ER', 'ET', 'KE', 'MG', 'MU', 'RW', 'SO', 'TZ', 'UG', 'BI', 'DJ', 'SS'],
  'southern-africa': ['BW', 'MW', 'MZ', 'NA', 'ZA', 'ZM', 'ZW', 'LS', 'SZ'],
};
const regionOf = (code) => Object.keys(REGIONS).find((r) => REGIONS[r].includes(code)) ?? null;

const geoms = world.objects.countries.geometries.filter((g) => ISO[g.id] || g.properties.name === 'Somaliland');
for (const g of geoms) if (ISO[g.id] && ISO[g.id][1] !== g.properties.name) throw new Error(`id ${g.id} is ${g.properties.name}, expected ${ISO[g.id][1]}`);
const missing = Object.keys(ISO).filter((id) => !geoms.some((g) => g.id === id));
if (missing.length) throw new Error('not in data: ' + missing);

const fc = topojson.feature(world, { type: 'GeometryCollection', geometries: geoms });
const W = 400, H = 430;
const projection = d3.geoAzimuthalEqualArea().rotate([-18, -2]).fitExtent([[8, 8], [W - 8, H - 8]], fc);
const path = d3.geoPath(projection).digits(0);

const countries = fc.features.map((f) => {
  // Somaliland is drawn as part of Somalia, as most maps do.
  const code = f.properties.name === 'Somaliland' ? 'SO' : ISO[f.id][0];
  const c = projection(d3.geoCentroid(f));
  return { code, region: code === 'EH' ? null : regionOf(code), d: path(f), at: [Math.round(c[0]), Math.round(c[1])] };
});
// Region label points: the centroid of each region's merged outline, nudged where it falls in the sea or off-shape.
const labels = {};
for (const r of Object.keys(REGIONS)) {
  const members = geoms.filter((g) => r === regionOf(g.properties.name === 'Somaliland' ? 'SO' : ISO[g.id][0]) && !(ISO[g.id]?.[0] === 'MG'));
  const merged = topojson.merge(world, members);
  const [x, y] = projection(d3.geoCentroid(merged));
  labels[r] = [Math.round(x), Math.round(y)];
}
const out = `/**
 * Africa, for the region maps: Natural Earth 1:110m country outlines (public
 * domain, via the world-atlas package), projected (azimuthal equal-area,
 * centred on 18°E 2°N) into a ${W}×${H} SVG viewBox and grouped by the site's
 * regions. Countries the site does not tag are drawn in their conventional
 * region so the continent is complete; Western Sahara belongs to none.
 * Small islands (Cape Verde, Mauritius, Comoros, São Tomé, Seychelles) are
 * below this scale.
 *
 * Generated by scripts/build-africa-map.mjs: do not edit by hand.
 */

export const AFRICA_VIEWBOX = '0 0 ${W} ${H}';

export interface MapCountry {
    /** ISO 3166-1 alpha-2. */
    code: string;
    /** A key of REGIONS, or null (Western Sahara). */
    region: string | null;
    d: string;
    /** Centroid, for a marker on countries too small to see. */
    at: [number, number];
}

export const AFRICA_COUNTRIES: MapCountry[] = ${JSON.stringify(countries)};

/** Where each region's name is written on the map. */
export const REGION_LABELS: Record<string, [number, number]> = ${JSON.stringify(labels)};
`;
writeFileSync(new URL('../src/content/africa-map.ts', import.meta.url), out);
console.log(countries.length, 'countries', Math.round(out.length / 1024), 'KB', labels);
