// build-motifs.mjs — writes src/app/motifs.css: the site's pattern library.
//
// Every decorative surface (card bands, article covers, the hero quilt, the
// loom band) is built from these tiles, set as CSS background images, so a
// page carries only class names: the library is one cached stylesheet, not
// SVG repeated in every card. The shapes are plain geometry — stripes, steps,
// diamonds, zigzags, dot rows, rings — in the site's earth palette; they do
// not copy any particular textile, artwork or symbol.
//
// The tiles and palettes live in src/lib/motifs.ts. Run after changing them:
//   node scripts/build-motifs.mjs
import { writeFileSync } from 'node:fs';

import { PALETTES, TILES } from '../src/lib/motifs.ts';

const uri = (svg) => `url("data:image/svg+xml,${svg.replace(/"/g, "'").replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E')}")`;

/** The stylesheet text: one class per tile and palette. */
export function motifsCss() {
    let css = `/* Generated by scripts/build-motifs.mjs — do not edit by hand. */\n`;
    TILES.forEach(([w, h, body], k) => {
        PALETTES.forEach(([a, b, c], p) => {
            const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}">${body(a, b, c)}</svg>`;
            css += `.mtf-${k}-${p}{background-image:${uri(svg)};background-size:${w}px ${h}px;--tw:${w}px}\n`;
        });
    });
    return css;
}

if (import.meta.url === `file://${process.argv[1]}`) {
    const css = motifsCss();
    writeFileSync(new URL('../src/app/motifs.css', import.meta.url), css);
    console.log(`${TILES.length * PALETTES.length} motifs, ${Math.round(css.length / 1024)} KB`);
}
